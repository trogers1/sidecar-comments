package runner

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// behaviorInventory is a seed inventory, not a claim that the listed seeds
// exhaust the normative specification. Seeded entries have a direct fixture;
// required_red entries name mandatory packs whose fixtures do not yet exist.
type behaviorInventory struct {
	InventoryVersion int    `json:"inventory_version"`
	PackRequiredRed  string `json:"pack_required_red"`
	Requirements     struct {
		Documents []string `json:"documents"`
		Plan      string   `json:"plan"`
	} `json:"requirements"`
	Behaviors   []inventoryBehavior `json:"behaviors"`
	RequiredRed []requiredRed       `json:"required_red"`
}
type inventoryBehavior struct {
	ID       string   `json:"id"`
	Fixtures []string `json:"fixtures"`
}
type requiredRed struct {
	ID     string `json:"id"`
	Reason string `json:"reason"`
}
type coverageMapping struct {
	CoverageVersion int             `json:"coverage_version"`
	Fixtures        []coverageEntry `json:"fixtures"`
}
type coverageEntry struct {
	ID       string `json:"id"`
	Behavior string `json:"behavior"`
}

func decodeInventory(path string) (behaviorInventory, error) {
	var inventory behaviorInventory
	data, err := readUnique(path)
	if err != nil {
		return inventory, err
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err = decoder.Decode(&inventory); err != nil {
		return inventory, fmt.Errorf("behavior inventory: %w", err)
	}
	if decoder.Decode(&struct{}{}) != io.EOF {
		return inventory, fmt.Errorf("behavior inventory: trailing JSON")
	}
	return inventory, nil
}

func expectedCoverage(inventory behaviorInventory) coverageMapping {
	mapping := coverageMapping{CoverageVersion: 1}
	for _, behavior := range inventory.Behaviors {
		for _, fixture := range behavior.Fixtures {
			mapping.Fixtures = append(mapping.Fixtures, coverageEntry{ID: fixture, Behavior: behavior.ID})
		}
	}
	return mapping
}

// validateCoverageMapping generates the corpus coverage mapping from the seed
// inventory and validates it in both directions. It intentionally has no
// hand-maintained rendered table: corpus fixture coverage must exactly match
// the mapping generated by the inventory.
func validateCoverageMapping(c corpus, inventory behaviorInventory) error {
	mapping := expectedCoverage(inventory)
	corpusCoverage := make(map[string]string)
	for _, fixture := range c.Fixtures {
		if _, duplicate := corpusCoverage[fixture.ID]; duplicate {
			return fmt.Errorf("coverage mapping duplicates fixture %s", fixture.ID)
		}
		corpusCoverage[fixture.ID] = fixture.Coverage[0]
	}
	if len(corpusCoverage) != len(mapping.Fixtures) {
		return fmt.Errorf("coverage mapping has orphaned seed or fixture")
	}
	for _, entry := range mapping.Fixtures {
		if corpusCoverage[entry.ID] != entry.Behavior {
			return fmt.Errorf("coverage mapping drift for fixture %s", entry.ID)
		}
	}
	return nil
}

func validateBehaviorInventory(base string, c corpus) error {
	path := filepath.Join(base, "contracts/behavior-inventory-v1.json")
	inventory, err := decodeInventory(path)
	if err != nil {
		return err
	}
	if inventory.InventoryVersion != 1 || inventory.PackRequiredRed != "contracts/packs/required-red-v1.json" || inventory.Requirements.Plan != "plans/initial.md" || len(inventory.Requirements.Documents) == 0 {
		return fmt.Errorf("invalid behavior inventory header")
	}
	if _, err := validateRequiredRedRegistry(base); err != nil {
		return fmt.Errorf("pack required-red inventory: %w", err)
	}
	for _, document := range inventory.Requirements.Documents {
		if !strings.HasPrefix(document, "docs/v1/") {
			return fmt.Errorf("invalid inventory document %s", document)
		}
		info, statErr := os.Stat(filepath.Join(base, document))
		if statErr != nil || !info.Mode().IsRegular() {
			return fmt.Errorf("stale inventory document %s", document)
		}
	}
	plan, statErr := os.Stat(filepath.Join(base, inventory.Requirements.Plan))
	if statErr != nil || !plan.Mode().IsRegular() {
		return fmt.Errorf("stale inventory plan")
	}
	byFixture, byBehavior := make(map[string]string), make(map[string]bool)
	for _, ref := range c.Fixtures {
		byFixture[ref.ID] = ref.Coverage[0]
	}
	for _, behavior := range inventory.Behaviors {
		if !strings.HasPrefix(behavior.ID, "BHV-") || byBehavior[behavior.ID] || len(behavior.Fixtures) == 0 {
			return fmt.Errorf("invalid inventory behavior %q", behavior.ID)
		}
		byBehavior[behavior.ID] = true
		for _, fixture := range behavior.Fixtures {
			if byFixture[fixture] != behavior.ID {
				return fmt.Errorf("inventory behavior %s lacks direct fixture %s", behavior.ID, fixture)
			}
		}
	}
	for fixture, behavior := range byFixture {
		if !byBehavior[behavior] {
			return fmt.Errorf("orphan fixture/behavior %s/%s", fixture, behavior)
		}
	}
	redIDs := make(map[string]bool)
	for _, obligation := range inventory.RequiredRed {
		if !strings.HasPrefix(obligation.ID, "BHV-") || obligation.Reason == "" || redIDs[obligation.ID] || byBehavior[obligation.ID] {
			return fmt.Errorf("invalid required-red obligation %q", obligation.ID)
		}
		redIDs[obligation.ID] = true
	}
	if len(inventory.RequiredRed) == 0 {
		return fmt.Errorf("missing required-red obligations")
	}
	return validateCoverageMapping(c, inventory)
}

// RequiredRedObligations returns mandatory packs without fixtures. It is used
// by the full release gate so a partial seed corpus cannot accidentally pass.
func RequiredRedObligations(corpusPath string) ([]string, error) {
	if corpusPath == "" {
		corpusPath = "contracts/corpus/v1.json"
	}
	base, err := repoRoot(corpusPath)
	if err != nil {
		return nil, err
	}
	inventory, err := decodeInventory(filepath.Join(base, "contracts/behavior-inventory-v1.json"))
	if err != nil {
		return nil, err
	}
	out := make([]string, 0, len(inventory.RequiredRed))
	for _, obligation := range inventory.RequiredRed {
		out = append(out, obligation.ID+": "+obligation.Reason)
	}
	packObligations, err := requiredRedScenarioLines(base)
	if err != nil {
		return nil, err
	}
	return append(out, packObligations...), nil
}
